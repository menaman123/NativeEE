#!/usr/bin/env python3
"""gen_gl_loader.py -- generate engine/platform/windows/gl_loader.h, the Windows arm of PS2R_GL_HEADER.

Windows' opengl32.dll exports OpenGL 1.1 only; every later entry point (and, portably, every entry point) comes from
the installable client driver through wglGetProcAddress -- SDL_GL_GetProcAddress wraps both. macOS and Linux export
the core profile from the GL library itself, so the engine calls `glXxx(...)` directly there. On Windows the same call
sites compile against this generated header: Khronos' <GL/glcorearb.h> (vcpkg port `opengl-registry`) for the types,
enums and PFNGL*PROC typedefs, and for EVERY GL function the engine calls a function pointer `ps2r_glwin_glXxx` behind
the GL name (a macro), filled by ps2r::glwin::Load() once the context is current (engine/platform/sdl/gl_context.cpp).

The function list is the tree's: this script scans every .cpp/.h under engine/ app/ games/ tools/ tests/ (not
third_party/) for `gl[A-Z]...(` call sites outside comments and strings. Adding a GL call to the engine means re-running
it (ctest PlatformGlLoaderCurrent fails until the header is regenerated):

    python3 tools/build/gen_gl_loader.py            # rewrite engine/platform/windows/gl_loader.h
    python3 tools/build/gen_gl_loader.py --check    # exit 1 when the committed header is not what the tree needs
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "engine", "platform", "windows", "gl_loader.h")
SCAN_DIRS = ("engine", "app", "games", "tools", "tests")
GL_CALL = re.compile(r"\bgl([A-Z][A-Za-z0-9]*)\s*\(")
# Entry points newer than the 4.1 core the engine requires: resolved when the driver has them (the pointer stays null
# otherwise), never a reason to refuse the context. Their call sites test the pointer first.
OPTIONAL = {"glClipControl"}


def scan(root):
    used = set()
    for top in SCAN_DIRS:
        for dirpath, dirnames, filenames in os.walk(os.path.join(root, top)):
            dirnames[:] = [d for d in dirnames if d != "third_party" and not d.startswith(".")]
            for f in filenames:
                if not f.endswith((".cpp", ".h", ".hpp", ".c", ".inc")):
                    continue
                p = os.path.join(dirpath, f)
                if os.path.abspath(p) == OUT:
                    continue
                try:
                    t = open(p, encoding="utf-8", errors="ignore").read()
                except OSError:
                    continue
                t = re.sub(r"//[^\n]*", "", t)
                t = re.sub(r"/\*.*?\*/", "", t, flags=re.S)
                t = re.sub(r'"(?:\\.|[^"\\])*"', '""', t)
                for m in GL_CALL.finditer(t):
                    used.add("gl" + m.group(1))
    return sorted(used)


def render(names):
    lines = [
        "// engine/platform/windows/gl_loader.h -- GENERATED by tools/build/gen_gl_loader.py from the tree's GL call sites.",
        "// Do not edit: re-run the script (ctest PlatformGlLoaderCurrent compares). The Windows arm of PS2R_GL_HEADER",
        "// (engine/platform/host/platform.h): Windows' opengl32.dll exports GL 1.1 only, the rest comes from the driver",
        "// through wglGetProcAddress, so every GL entry point the engine calls is a function pointer here, named",
        "// ps2r_glwin_<gl name> and reached through the GL name (a macro, so the call sites read as on macOS / Linux).",
        "// ps2r::glwin::Load() fills them once a context is current (engine/platform/sdl/gl_context.cpp, SDL_GL_GetProcAddress).",
        "// Types, enums and the PFNGL*PROC typedefs come from Khronos' glcorearb.h (vcpkg port opengl-registry;",
        "// cmake/OpenGlDependency.cmake puts it on OpenGL::GL's include path on Windows).",
        "#pragma once",
        "#if !defined(_WIN32)",
        '#error "engine/platform/windows/gl_loader.h is the Windows GL arm; other hosts include PS2R_GL_HEADER from engine/platform/host/platform.h"',
        "#endif",
        "#ifdef GL_GLEXT_PROTOTYPES",
        "#undef GL_GLEXT_PROTOTYPES   // never prototypes here: the entry points are the pointers below",
        "#endif",
        "#ifndef NOMINMAX",
        "#define NOMINMAX 1           // glcorearb.h includes <windows.h> for APIENTRY",
        "#endif",
        "#ifndef WIN32_LEAN_AND_MEAN",
        "#define WIN32_LEAN_AND_MEAN 1",
        "#endif",
        "#include <GL/glcorearb.h>",
        "",
        "// X(type, gl name) for every entry point the engine requires (%d)." % len([n for n in names if n not in OPTIONAL]),
        "#define PS2R_GLWIN_FUNCS(X) \\",
    ]
    required = [n for n in names if n not in OPTIONAL]
    optional = [n for n in names if n in OPTIONAL]
    for i, n in enumerate(required):
        pfn = "PFN" + n.upper() + "PROC"
        lines.append("    X(%s, %s)%s" % (pfn, n, " \\" if i + 1 < len(required) else ""))
    lines += [
        "",
        "// X(type, gl name) for the entry points used when the driver has them (the pointer null otherwise).",
        "#define PS2R_GLWIN_OPTIONAL_FUNCS(X)%s" % (" \\" if optional else ""),
    ]
    for i, n in enumerate(optional):
        pfn = "PFN" + n.upper() + "PROC"
        lines.append("    X(%s, %s)%s" % (pfn, n, " \\" if i + 1 < len(optional) else ""))
    lines += [
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
    ]
    for n in names:
        lines.append("extern PFN%sPROC ps2r_glwin_%s;" % (n.upper(), n))
    lines += [
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "// The GL names resolve to the pointers.",
    ]
    for n in names:
        lines.append("#define %s ps2r_glwin_%s" % (n, n))
    lines += [
        "",
        "#ifdef __cplusplus",
        "namespace ps2r {",
        "namespace glwin {",
        "// Fill every pointer through `getproc` (SDL_GL_GetProcAddress once a context is current). Returns how many",
        "// required entry points the driver did not supply and writes up to `max_missing` of their names into `missing`.",
        "int Load(void* (*getproc)(const char*), const char** missing, int max_missing);",
        "// The number of required entry points in the table (the generated count).",
        "int Count();",
        "}  // namespace glwin",
        "}  // namespace ps2r",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    names = scan(ROOT)
    text = render(names)
    if check:
        try:
            current = open(OUT, encoding="utf-8").read()
        except OSError:
            current = None
        if current != text:
            print("gen_gl_loader: %s is out of date (the tree calls %d GL entry points) -- run tools/build/gen_gl_loader.py" % (OUT, len(names)))
            return 1
        print("gen_gl_loader: %s current (%d entry points)" % (OUT, len(names)))
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("gen_gl_loader: wrote %s (%d entry points)" % (OUT, len(names)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
