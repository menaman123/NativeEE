#!/usr/bin/env python3
"""Continuation metadata + dispatch instrumentation post-pass.

Reads emitted C++, never the game at runtime. Does not write body shards.
Run after the normal generator and before recording the output manifest.
--check verifies deterministic sidecar output and the instrumented common TU.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path


FUNCTION = re.compile(r"^// Function: (\w+) at (0x[0-9a-f]+)\n"
                      r"void \1\(CpuContext& ctx, uint32_t addr\) \{", re.M)
# The default registration, in the classic lambda form and in the compact form the
# generator's --init-parts > 1 emits (`= &FUN_...;` -- the same body, no closure type).
DEFAULT = re.compile(
    r"(    recompiled_functions\[(0x[0-9a-f]+)\] = )"
    r"((?:\[\]\(CpuContext& ctx, uint32_t addr\) \{ (?:FUN_\w+|entry)\(ctx, addr\); \})"
    r"|&(?:FUN_\w+|entry));")
AUDITS = json.loads(Path(__file__).with_name("continuation_audits.json").read_text())


def audited(kind, address, text):
    record = AUDITS[kind].get(hex(address))
    return bool(record and record["sha256"] == hashlib.sha256(text.encode()).hexdigest())


def collect(shards):
    records = []
    hashes = []
    for path in shards:
        source = path.read_text()
        hashes.append((path.name, hashlib.sha256(path.read_bytes()).hexdigest()))
        functions = list(FUNCTION.finditer(source))
        for index, match in enumerate(functions):
            address = int(match[2], 16)
            end = functions[index + 1].start() if index + 1 < len(functions) else len(source)
            body = source[match.end():end]
            start = re.search(r"^Label_0000: // 0x[0-9a-f]+\n", body, re.M)
            # Handwritten/manual bodies need an explicit independent proof.
            if not start or not body.startswith("\nbool branch_taken;\nbool cond;\n"):
                continue
            prefix = body[:start.start()]
            # Only the ordinary generator's inert local initialization may run
            # before a resume switch. Diagnostic/special prologues require audit.
            raw_prologue = prefix.split("    switch (addr)")[0]
            prologue = raw_prologue
            prologue = re.sub(
                r"bool branch_taken;|bool cond;|uint64_t _native_saved_r\d+ = 0;|"
                r"bool _native_valid = false; \(void\)_native_valid;|"
                r"initialize_recompiled_functions\(\);", "", prologue)
            if prologue.strip() and not audited("prologues", address, raw_prologue):
                continue
            entries = {address}
            labels = set(re.findall(r"^(\w+):", body, re.M))
            for entry, label in re.findall(r"case (0x[0-9a-f]+): goto (\w+);", prefix):
                if label not in labels:
                    raise ValueError(f"{path}: {entry} has no emitted target {label}")
                entries.add(int(entry, 16))
            # Restart only literal syscall thunks with no earlier side effects.
            # Match the whole body, so inserting a store/call invalidates proof.
            first_block = body[start.end():]
            following_label = re.search(r"^Label_\w+:", first_block, re.M)
            if following_label:
                first_block = first_block[:following_label.start()]
            else:
                first_block = first_block.rstrip()[:-1]  # function closing brace
            normalized = re.sub(r"//[^\n]*", "", first_block)
            normalized = re.sub(r"\s+", "", normalized)
            wait = 0
            for syscall, kind in ((0x32, 1), (0x44, 2), (0x56, 3)):
                expected = (
                    "{"
                    "ctx.cpuRegs.GPR.r[3].SD[0]=static_cast<int32_t>("
                    "static_cast<int32_t>(ctx.cpuRegs.GPR.r[0].SL[0])+"
                    f"0x{syscall:x});"
                    "runtime_syscall_dispatcher(ctx.cpuRegs.GPR.r[3].UL[0],ctx);"
                    "return;}")
                if normalized == expected:
                    wait = kind
            records.append((address, sorted(entries), wait))
    records.sort()
    if len({r[0] for r in records}) != len(records):
        raise ValueError("duplicate generated body")
    return records, hashes


def metadata(records, hashes):
    lines = ["// Generated by tools/recompiler_v2/continuations.py; do not hand edit.",
             "// Exact emitted entry switches. Body-shard SHA-256 provenance:"]
    lines += [f"// {name} {digest}" for name, digest in hashes]
    lines += ['#include "engine/ee/cpu/dispatch_table.h"', "#include <algorithm>",
              "namespace {", "const uint32_t continuation_entries[] = {"]
    flat = [entry for _, entries, _ in records for entry in entries]
    for i in range(0, len(flat), 10):
        lines.append("    " + ", ".join(f"0x{x:x}u" for x in flat[i:i + 10]) + ",")
    lines += ["};", "struct ContinuationRow { uint32_t fn, offset, count; int wait; };",
              "const ContinuationRow continuation_rows[] = {"]
    offset = 0
    for address, entries, wait in records:
        lines.append(f"    {{0x{address:x}u, {offset}u, {len(entries)}u, {wait}}},")
        offset += len(entries)
    lines += ["};", "DispatchTable::Continuations recomp_continuations(uint32_t fn) {",
              "    const auto* end = std::end(continuation_rows);",
              "    const auto* row = std::lower_bound(std::begin(continuation_rows), end, fn,",
              "        [](const ContinuationRow& item, uint32_t key) { return item.fn < key; });",
              "    if (row == end || row->fn != fn) return {};",
              "    return {continuation_entries + row->offset, row->count, row->wait};",
              "}", "} // namespace", ""]
    return "\n".join(lines)


def instrument_audited_wrappers(source):
    wrapped = re.compile(r"DispatchTable::GeneratedBody\((0x[0-9a-f]+), "
                         r"(\[\]\(CpuContext& ctx, uint32_t addr\) \{\n.*?\n    \}), "
                         r"recomp_continuations\(\1\)\)", re.S)
    # Rechecking an already instrumented TU must revoke a stale audit too.
    source = wrapped.sub(lambda m: m[0] if audited("wrappers", int(m[1], 16), m[2]) else m[2], source)
    pattern = re.compile(r"(    recompiled_functions\[(0x[0-9a-f]+)\] = )"
                         r"(\[\]\(CpuContext& ctx, uint32_t addr\) \{.*?\n    \});", re.S)
    def replace(match):
        if not audited("wrappers", int(match[2], 16), match[3]):
            return match[0]
        return (match[1] + f"DispatchTable::GeneratedBody({match[2]}, {match[3]}, "
                f"recomp_continuations({match[2]}));")
    return pattern.sub(replace, source)


def instrument(source):
    if '// [CONTINUATION-PROOF]' in source:
        return instrument_audited_wrappers(source)
    source = '// [CONTINUATION-PROOF]\n#include "continuations.h"\n' + source
    source = source.replace('#include "continuations.h"\n',
                            '#include "continuations.h"\n'
                            '#include "engine/ee/cpu/shadow_call_stack.h"\n', 1)
    source, count = DEFAULT.subn(
        lambda m: m[1] + f"DispatchTable::GeneratedBody({m[2]}, {m[3]}, "
        f"recomp_continuations({m[2]}));", source)
    if not count:
        raise ValueError("no default registrations found")
    changes = {
        "    rf_it->second = new_impl;":
            "    const auto observed = DispatchTable::ObserveInstall(addr, new_impl);\n"
            "    rf_it->second = observed;",
        "r.func = new_impl;": "r.func = observed;",
        "g_sorted_func_impls[idx] = new_impl;": "g_sorted_func_impls[idx] = observed;",
        "        it->second = [original, addr](CpuContext& ctx, uint32_t call_addr) {":
            "        auto traced = [original, addr](CpuContext& ctx, uint32_t call_addr) {",
        "            original(ctx, call_addr);\n        };\n    }\n    // Update function_ranges":
            "            original(ctx, call_addr);\n        };\n"
            "        it->second = DispatchTable::TraceBody(addr, original, std::move(traced));\n"
            "    }\n    // Update function_ranges",
        "    if (g_ee_call_stack_depth >= EE_CALL_STACK_MAX) return false;":
            "    if (g_ee_call_stack_depth >= EE_CALL_STACK_MAX) {\n"
            "        ShadowCallStack::RejectedPush();\n        return false;\n    }",
        "    if (g_ee_call_stack_depth > 0) --g_ee_call_stack_depth;\n}":
            "    if (g_ee_call_stack_depth > 0) --g_ee_call_stack_depth;\n"
            "    if (!g_ee_call_stack_depth) ShadowCallStack::StackEmptied();\n}",
        "            pushed = true;\n        }\n    }\n    ~EeCallFrameGuard()":
            "            pushed = true;\n        } else {\n"
            "            ShadowCallStack::RejectedPush();\n        }\n    }\n"
            "    ~EeCallFrameGuard()",
        "        if (pushed && g_ee_call_stack_depth > 0) --g_ee_call_stack_depth;":
            "        if (pushed) ee_call_stack_pop();",
    }
    for before, after in changes.items():
        if source.count(before) != 1:
            raise ValueError(f"common TU contract changed: {before!r}")
        source = source.replace(before, after)
    return instrument_audited_wrappers(source)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--stack-fixture", type=Path,
                        help="extract ONLY common stack ABI for isolated tests")
    args = parser.parse_args()
    if args.stack_fixture:
        source = (args.directory / "recompiled.cpp").read_text()
        begin = source.index("struct EeCallFrame {")
        end = source.index("\nstd::map<uint32_t", begin)
        args.stack_fixture.write_text(
            "// Generated common stack ABI only: no title bodies.\n" + source[begin:end])
        return
    shards = sorted(args.directory.glob("recompiled_shard_*.cpp"))
    if not shards:
        parser.error("no generated body shards")
    records, hashes = collect(shards)
    common = args.directory / "recompiled.cpp"
    outputs = {args.directory / "continuations.h": metadata(records, hashes),
               common: instrument(common.read_text())}
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"stale continuation output: {path}")
        else:
            path.write_text(text)
    print(f"continuations: {len(records)} bodies, "
          f"{sum(len(x[1]) for x in records)} exact entries, "
          f"{sum(bool(x[2]) for x in records)} restartable wait thunks; "
          f"{len(shards)} body shards unchanged")


if __name__ == "__main__":
    main()
