#pragma once
// app/gui/fps_overlay.h -- the FPS counter drawn over the presented frame (video.fps_overlay).
//
// Two parts, both title-neutral:
//   FpsHistory   (fps_history.h) the statistics: every picture SHOWN by the presenter (SessionWindow::Show /
//                Upload = a new picture on the screen, never a re-draw of the same one) is noted
//                with its time; Compute() gives the pictures per second over the last 0.5 s, the
//                mean frame time of that window and the per-picture gaps of the last ~2.5 s (the
//                sparkline: where a drop was and by how much). Pure arithmetic, tested alone.
//   DrawFpsOverlay  the renderer: the stroke glyph set of fps_glyphs.inc (an original design
//                generated by tools/gen_fps_glyphs.py -- no game asset) through ImDrawList, an
//                outline pass under a fill pass, the fps figure coloured by FpsColour (green at
//                60, amber 50-59, red below), the labels and the panel in the colours of a theme
//                the title supplies (FpsOverlayTheme; the default is a neutral grey/white).
//
// Cost: a handful of polylines + up to kHistory small rectangles per presented frame; measured
// under 0.1 ms (SessionGui::FpsOverlayCensus reports draws, mean and max microseconds).
#include <cstddef>
#include <cstdint>

#include "app/gui/fps_history.h"

struct ImDrawList;

namespace ps2r::app {

struct FpsOverlayTheme {
    // ImGui-packed colours (IM_COL32: A<<24 | B<<16 | G<<8 | R).
    uint32_t outline = 0xE0101010;        // the glyph outline (a dark edge under every stroke)
    uint32_t label = 0xFFE6E6E6;          // "fps" / "ms" and the frame-time figure
    uint32_t panel = 0x8C000000;          // the backing panel
    uint32_t panel_border = 0x60FFFFFF;   // its rim
    uint32_t spark_frame = 0x60FFFFFF;    // the sparkline's 60 Hz reference line
};

// The fps figure's colour: green at 60 (>= 59.5), amber 50..59.5, red below.
uint32_t FpsColour(float fps);
// One gap's colour for the sparkline (the same thresholds in gap terms: a gap of 16.67 ms is 60).
uint32_t GapColour(float gap_ms);

// Width of a text in glyph cells at `cell_h` pixels per cell height (the layout helper the
// renderer and its test share). Unknown characters take a space of half a cell.
float FpsTextWidth(const char* text, float cell_h);

// Draws the counter with its top-right corner at (right_x, top_y). `cell_h` = the pixel height of
// the fps figure's digits (the frame-time line is drawn at 0.5 of it); the whole panel scales with
// it. Returns the panel's height in pixels (for stacking another overlay under it).
float DrawFpsOverlay(ImDrawList* draw, float right_x, float top_y, float cell_h, const FpsHistory::Stats& stats,
                     const FpsOverlayTheme& theme);

}  // namespace ps2r::app
