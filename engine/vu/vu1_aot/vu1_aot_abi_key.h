#pragma once
// Vu1AotAbiKey -- the identity a GENERATED VU1 image library is binary-compatible
// with: SHA-256 over the staged prelude closure (every header the emitted TU
// includes, in MANIFEST.txt order: its tree-relative path, a newline, its bytes,
// a NUL) followed by one `define=NAME=VAL` line per preprocessor definition the
// engine was built with (sorted) -- rendered as `abi-<first 16 hex digits>`.
//
// The key covers what the TU compiles against (the slot layout, the inlined
// bodies, the hazard tables); the engine's non-inline symbols the library binds
// at load are the running binary's own. Two engine builds from the same VU
// sources share the key, so a library built on one machine (the pre-built pack,
// tools/vu1_aot_pack) loads on another; the build-time constant
// kVu1AotAbiKey (generated by tools/vu1_aot_stage_prelude.py into
// vu1_aot_abi_key.h) is this function over the build's own staging, and the
// test pins the two equal. A loaded library is still re-verified on the image's
// corpus before it runs (the gate every tier passes), so the key is a filter,
// never the proof.
#include <string>
#include <vector>

class Vu1AotAbiKey {
public:
    // The key of the prelude tree under `prelude_dir` (its MANIFEST.txt lists the
    // files). Empty on failure (`err` says why).
    static std::string Compute(const std::string& prelude_dir, const std::vector<std::string>& defines, std::string* err);
    // The definitions this engine binary was built with, in the staging script's
    // `NAME=VAL` grammar (PS2R_SIMD=1 when SIMD is on; nothing otherwise).
    static std::vector<std::string> BuildDefines();
    // Compute with BuildDefines().
    static std::string ComputeForThisBuild(const std::string& prelude_dir, std::string* err);
};
